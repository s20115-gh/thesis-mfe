// ESLint for the whole repo. Type-aware rules use the TypeScript 6 API
// (`typescript` is aliased to @typescript/typescript6, because TypeScript 7
// has no API yet). See docs/decisions.md.
import js from '@eslint/js'
import prettier from 'eslint-config-prettier'
import reactHooks from 'eslint-plugin-react-hooks'
import { defineConfig, globalIgnores } from 'eslint/config'
import globals from 'globals'
import tseslint from 'typescript-eslint'

// A string that starts like one of the app's own URLs.
const appPath = String.raw`/^\/(salons|venues|book|checkout|account|merchant|sign-in)(\/|\?|$)/`
const hardCodedPathMessage =
  'Hard-coded app URL. Use paths or basePaths from @thesis/contracts, so links keep working wherever the shell mounts a feature.'

export default defineConfig([
  // database.ts is generated by `pnpm db:types`.
  globalIgnores([
    '**/dist',
    '**/.mf',
    'spike/**',
    'packages/contracts/src/database.ts',
    '**/playwright-report',
    '**/test-results',
  ]),

  // TypeScript sources (apps and packages)
  {
    files: ['**/*.{ts,tsx}'],
    extends: [
      js.configs.recommended,
      tseslint.configs.recommendedTypeChecked,
      reactHooks.configs.flat.recommended,
    ],
    languageOptions: {
      globals: globals.browser,
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
  },

  // Features link to each other only through the URL contract in
  // @thesis/contracts (paths, basePaths), never through hard-coded strings.
  // Together with dependency-cruiser's no-cross-feature-imports this means
  // the only coupling between features is the shared list of URLs.
  {
    files: ['packages/features/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-syntax': [
        'error',
        {
          selector: `Literal[value=${appPath}]`,
          message: hardCodedPathMessage,
        },
        {
          selector: `TemplateElement[value.raw=${appPath}]`,
          message: hardCodedPathMessage,
        },
      ],
    },
  },

  // Playwright fixtures call a function named `use`, which the React hooks
  // rules mistake for React's use() hook.
  {
    files: ['e2e/**/*.ts'],
    rules: { 'react-hooks/rules-of-hooks': 'off' },
  },

  // Node scripts
  {
    files: ['**/*.{js,mjs}'],
    extends: [js.configs.recommended],
    languageOptions: { globals: globals.node },
  },

  // Must be last: turns off rules that clash with Prettier formatting.
  prettier,
])
